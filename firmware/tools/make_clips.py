"""Generates the glasses' voice clips from the app's clip table.

Reads the clip numbers and Arabic words from app/lib/data/obstacles.dart (the
phone sends only clip numbers), speaks each with a Saudi Arabic neural voice,
and writes:

  baseera_glasses/clips.h, clips.cpp   16 kHz mono PCM compiled into the firmware
  tools/clips/<n>_<name>.wav           the same clips, to listen to

Setup once (keep the venv on D: — C: is full):
    python -m venv .venv
    .venv\\Scripts\\pip install edge-tts miniaudio
Run (needs internet), then rebuild the firmware:
    .venv\\Scripts\\python make_clips.py
    .venv\\Scripts\\python make_clips.py --voice ar-SA-ZariyahNeural   # female voice
"""

import argparse
import array
import asyncio
import re
import tempfile
import wave
from pathlib import Path

import edge_tts
import miniaudio

HERE = Path(__file__).resolve().parent
OBSTACLES_DART = HERE.parent.parent / "app" / "lib" / "data" / "obstacles.dart"
SKETCH = HERE.parent / "baseera_glasses"
PREVIEW = HERE / "clips"
RATE = 16000

# Clips that aren't an object or a direction (GlassesClips in obstacles.dart).
SYSTEM_TEXT = {
    "veryClose": "قريب جداً",
    "connected": "تم الاتصال",
    "disconnected": "انقطع الاتصال بالجوال",
    "batteryLow": "البطارية منخفضة",
    "alertsOff": "التنبيهات متوقفة",
    "alertsOn": "التنبيهات تعمل",
}


def clip_table() -> dict[int, tuple[str, str]]:
    """clip number -> (name, Arabic text), straight from the app."""
    dart = OBSTACLES_DART.read_text(encoding="utf-8")
    clips: dict[int, tuple[str, str]] = {}
    for name, number, arabic in re.findall(r"^  (\w+)\((\d+), '([^']+)'", dart, re.M):
        clips[int(number)] = (name, arabic)
    for name, number in re.findall(r"static const (\w+) = (\d+);", dart):
        if name not in SYSTEM_TEXT:
            raise SystemExit(f"GlassesClips.{name} has no text in SYSTEM_TEXT")
        clips[int(number)] = (name, SYSTEM_TEXT[name])
    if not clips or max(clips) > 255:
        raise SystemExit("clip numbers must be 1..255 (sent as bytes)")
    return dict(sorted(clips.items()))


async def speak(text: str, voice: str, mp3: Path) -> None:
    await edge_tts.Communicate(text, voice, rate="+10%").save(str(mp3))


def to_pcm(mp3: Path) -> array.array:
    """Decode, trim the silence around the word, normalize the loudness."""
    decoded = miniaudio.decode_file(
        str(mp3),
        output_format=miniaudio.SampleFormat.SIGNED16,
        nchannels=1,
        sample_rate=RATE,
    )
    samples = array.array("h", decoded.samples)
    loud = [i for i, s in enumerate(samples) if abs(s) > 600]
    if not loud:
        raise SystemExit(f"{mp3.name}: no speech")
    margin = RATE * 30 // 1000
    samples = samples[max(0, loud[0] - margin) : loud[-1] + margin]
    peak = max(abs(s) for s in samples)
    gain = 0.9 * 32767 / peak
    return array.array("h", (int(s * gain) for s in samples))


def snake(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).upper()


def write_sources(clips: dict[int, tuple[str, str]], pcm: dict[int, array.array]) -> None:
    header = [
        "// Generated by tools/make_clips.py from app/lib/data/obstacles.dart.",
        "// Do not edit: change the app's clip table and run the script again.",
        "#pragma once",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        f"#define CLIP_RATE {RATE}",
        "",
    ]
    header += [f"#define CLIP_{snake(name)} {n}  // {text}" for n, (name, text) in clips.items()]
    header += [
        "",
        "struct Clip {",
        "  uint8_t id;",
        "  const int16_t *pcm;",
        "  uint32_t samples;",
        "};",
        "",
        "extern const Clip CLIPS[];",
        "extern const size_t CLIP_COUNT;",
        "",
    ]
    (SKETCH / "clips.h").write_text("\n".join(header), encoding="utf-8", newline="\n")

    body = ['// Generated by tools/make_clips.py. Do not edit.', '#include "clips.h"', ""]
    for n, (name, text) in clips.items():
        data = pcm[n]
        body.append(f"// {n}: {text}")
        body.append(f"static const int16_t clip{n}[{len(data)}] = {{")
        for i in range(0, len(data), 16):
            body.append("  " + ",".join(str(s) for s in data[i : i + 16]) + ",")
        body.append("};")
    body.append("")
    body.append("const Clip CLIPS[] = {")
    body += [f"  {{{n}, clip{n}, {len(pcm[n])}}}," for n in clips]
    body.append("};")
    body.append("const size_t CLIP_COUNT = sizeof(CLIPS) / sizeof(CLIPS[0]);")
    body.append("")
    (SKETCH / "clips.cpp").write_text("\n".join(body), encoding="utf-8", newline="\n")


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate the glasses' voice clips")
    parser.add_argument("--voice", default="ar-SA-HamedNeural")
    args = parser.parse_args()

    clips = clip_table()
    PREVIEW.mkdir(exist_ok=True)
    pcm: dict[int, array.array] = {}
    with tempfile.TemporaryDirectory(dir=HERE) as tmp:
        for n, (name, text) in clips.items():
            mp3 = Path(tmp) / f"{n}.mp3"
            asyncio.run(speak(text, args.voice, mp3))
            pcm[n] = to_pcm(mp3)
            with wave.open(str(PREVIEW / f"{n:03d}_{name}.wav"), "wb") as w:
                w.setnchannels(1)
                w.setsampwidth(2)
                w.setframerate(RATE)
                w.writeframes(pcm[n].tobytes())
            print(f"{n:>3} {name:<12} {len(pcm[n]) / RATE:4.2f}s  {text}")

    write_sources(clips, pcm)
    total = sum(len(p) for p in pcm.values()) * 2
    print(f"\n{len(clips)} clips, {total / 1024:.0f} KB of flash -> {SKETCH.name}/clips.cpp")


if __name__ == "__main__":
    main()
